<?php

namespace App\Console\Commands;

use App\Models\GalaxyImage;
use App\Models\Dataset;
use App\Models\DataSource;
use App\Models\MlModel;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

class DataImportGalaxies extends Command
{
    protected $signature = 'data:import-galaxies {--dataset= : Import only sdss or deca} {--force : Replace existing images and invalidate their trained model}';
    protected $description = 'Import galaxy images from prepared Galaxy10 data (generated by scripts/prepare_galaxy10.py)';

    public function handle(): int
    {
        $selected = $this->option('dataset');
        if ($selected && !in_array($selected, ['sdss', 'deca'], true)) {
            $this->error('Use --dataset=sdss or --dataset=deca.');
            return Command::FAILURE;
        }
        $dataFile = database_path('data/galaxies.json');
        if (!is_file($dataFile)) {
            $this->error('Run python3 scripts/prepare_galaxy10.py first; galaxies.json is missing.');
            return Command::FAILURE;
        }

        try {
            $data = json_decode(File::get($dataFile), true, 512, JSON_THROW_ON_ERROR);
            if (!is_array($data)) {
                throw new \RuntimeException('Prepared data must be a JSON object.');
            }
            $pending = [];
            $skipped = 0;
            foreach ($selected ? [$selected] : ['deca', 'sdss'] as $key) {
                $images = $data[$key] ?? [];
                if ($images === []) {
                    if ($selected) {
                        throw new \RuntimeException("No prepared images for {$key}. Run the preparation script for this dataset first.");
                    }
                    $this->line("Skipping {$key}: no prepared images; existing data is unchanged.");
                    continue;
                }
                $dataset = Dataset::where('mission_key', 'galaxy')->where('key', 'galaxy10_'.$key)->first();
                if ($dataset && $dataset->galaxyImages()->exists() && !$this->option('force')) {
                    $this->line("Skipping {$key}: already imported. Use --force to replace it.");
                    $skipped++;
                    continue;
                }
                $this->validateImages($images, $key);
                $pending[$key] = $images;
            }
            if (!$pending && !$skipped) {
                throw new \RuntimeException('No prepared Galaxy10 images found. Nothing was imported.');
            }
            // Validate every selected dataset before changing any database records.
            DB::transaction(function () use ($pending) {
                foreach ($pending as $key => $images) {
                    $this->importDataset($key, $images);
                }
                $ready = Dataset::where('mission_key', 'galaxy')->whereHas('galaxyImages');
                $default = (clone $ready)->where('is_default', true)->first() ?? $ready->first();
                if ($default) {
                    Dataset::where('mission_key', 'galaxy')->where('id', '!=', $default->id)->update(['is_default' => false]);
                    $default->update(['is_default' => true]);
                }
            });
            $this->info('Import complete: '.count($pending).' dataset(s) imported.');
            return Command::SUCCESS;
        } catch (\Throwable $e) {
            $this->error($e->getMessage());
            return Command::FAILURE;
        }
    }

    private function validateImages(mixed $images, string $key): void
    {
        if (!is_array($images) || !array_is_list($images)) {
            throw new \RuntimeException("{$key}: images must be a list.");
        }
        $allowed = $key === 'sdss' ? ['Elliptical', 'Spiral', 'Edge-on disk'] : ['Elliptical', 'Spiral', 'Irregular'];
        $seen = [];
        foreach ($images as $index => $image) {
            $prefix = "{$key} image {$index}";
            if (!is_array($image)) {
                throw new \RuntimeException("{$prefix}: invalid record.");
            }
            foreach (['source_id', 'original_label', 'image_path'] as $field) {
                if (!is_string($image[$field] ?? null) || trim($image[$field]) === '' || strlen($image[$field]) > 255) {
                    throw new \RuntimeException("{$prefix}: invalid {$field}.");
                }
            }
            if (isset($seen[$image['source_id']])) {
                throw new \RuntimeException("{$prefix}: duplicate source_id.");
            }
            $seen[$image['source_id']] = true;
            if (!in_array($image['label'] ?? null, $allowed, true) || !in_array($image['split'] ?? null, ['train', 'test'], true)) {
                throw new \RuntimeException("{$prefix}: invalid label or split.");
            }
            $pixels = $image['pixels'] ?? null;
            if (!is_array($pixels) || !array_is_list($pixels) || count($pixels) !== 256) {
                throw new \RuntimeException("{$prefix}: expected 256 normalized pixels.");
            }
            foreach ($pixels as $pixel) {
                if ((!is_int($pixel) && !is_float($pixel)) || !is_finite((float) $pixel) || $pixel < 0 || $pixel > 1) {
                    throw new \RuntimeException("{$prefix}: pixels must be numbers between 0 and 1.");
                }
            }
            $path = $image['image_path'];
            if (!preg_match('~^galaxies/[A-Za-z0-9_.-]+\.jpg$~', $path) || !is_file(storage_path('app/public/'.$path))) {
                throw new \RuntimeException("{$prefix}: missing or invalid JPEG path {$path}.");
            }
        }
    }

    private function importDataset(string $key, array $images): void
    {
        $title = $key === 'sdss' ? 'Galaxy10 SDSS' : 'Galaxy10 DECaLS';
        $url = 'https://astronn.readthedocs.io/en/stable/'.($key === 'sdss' ? 'galaxy10sdss.html' : 'galaxy10.html');
        $source = DataSource::updateOrCreate(
            ['key' => $key === 'sdss' ? 'galaxy10_sdss' : 'galaxy10_deca_ls'],
            [
                'title' => $title.' Dataset',
                'publisher' => 'astroNN / University of Toronto',
                'url' => $url,
                'license' => 'CC BY 4.0 (Galaxy Zoo labels) / '.($key === 'sdss' ? 'SDSS' : 'DESI Legacy Imaging Surveys'),
                'retrieved_at' => now(),
                'row_count' => count($images),
                'citation_text' => "{$title}, astroNN. Source: {$url}. Images from the survey; morphology labels from Galaxy Zoo.",
            ]
        );
        $labels = array_values(array_unique(array_column($images, 'label')));
        sort($labels);
        $dataset = Dataset::updateOrCreate(
            ['mission_key' => 'galaxy', 'key' => 'galaxy10_'.$key],
            [
                'title' => $title,
                'description' => 'Galaxy morphology classification using 16x16 grayscale images in '.count($labels).' broad classes.',
                'publisher' => $source->publisher, 'url' => $url, 'license' => $source->license,
                'row_count' => count($images), 'retrieved_at' => $source->retrieved_at,
                'citation_text' => $source->citation_text,
                'feature_schema' => ['pixels' => ['unit' => 'normalized 0-1', 'min' => 0, 'max' => 1, 'step' => 0.01]],
                'label_names' => $labels,
            ]
        );
        GalaxyImage::where('dataset_id', $dataset->id)->delete();
        MlModel::where('dataset_id', $dataset->id)->where('name', 'like', 'neural_network_galaxy_%')->delete();
        $rows = [];
        foreach ($images as $image) {
            $rows[] = [
                'source_id' => $image['source_id'], 'label' => $image['label'],
                'original_label' => $image['original_label'], 'image_path' => $image['image_path'],
                'pixels' => json_encode($image['pixels'], JSON_THROW_ON_ERROR), 'split' => $image['split'],
                'dataset_id' => $dataset->id, 'created_at' => now(), 'updated_at' => now(),
            ];
        }
        foreach (array_chunk($rows, 100) as $chunk) {
            GalaxyImage::insert($chunk);
        }
        $this->info("{$title}: ".count($rows).' images imported ('.implode(', ', $labels).').');
    }
}
